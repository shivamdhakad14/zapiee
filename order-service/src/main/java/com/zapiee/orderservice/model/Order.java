package com.zapiee.orderservice.model;

import com.zapiee.orderservice.enums.OrderStatus;
import jakarta.persistence.*;
import jakarta.validation.constraints.*;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Data;
import lombok.NoArgsConstructor;
import org.hibernate.annotations.CreationTimestamp;
import org.hibernate.annotations.UpdateTimestamp;

import java.math.BigDecimal;
import java.time.LocalDateTime;
import java.util.ArrayList;
import java.util.List;
import java.util.UUID;

@Entity
@Table(
        name = "orders",
        indexes = {

                @Index(
                        name = "idx_order_uuid",
                        columnList = "order_uuid"
                ),

                @Index(
                        name = "idx_restaurant_order",
                        columnList = "restaurant_id, order_uuid"
                ),

                @Index(
                        name = "idx_restaurant_status",
                        columnList = "restaurant_id, status"
                ),

                @Index(
                        name = "idx_restaurant_table",
                        columnList = "restaurant_id, table_id"
                ),

                @Index(
                        name = "idx_session_id",
                        columnList = "session_id"
                ),

                @Index(
                        name = "idx_restaurant_session",
                        columnList = "restaurant_id, session_id"
                ),

                @Index(
                        name = "idx_session_token",
                        columnList = "session_token"
                ),

                @Index(
                        name = "idx_restaurant_session_token",
                        columnList = "restaurant_id, session_token"
                ),

                @Index(
                        name = "idx_created_at",
                        columnList = "created_at"
                ),

                @Index(
                        name = "idx_restaurant_created_at",
                        columnList = "restaurant_id, created_at"
                )
        }
)
@Data
@NoArgsConstructor
@AllArgsConstructor
@Builder
public class Order {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    /**
     * Public/business identifier of the order.
     * Generated by Order Service.
     */
    @Column(
            name = "order_uuid",
            nullable = false,
            unique = true,
            updatable = false,
            length = 36
    )
    @NotBlank
    private String orderId;

    /**
     * Restaurant to which this order belongs.
     */
    @Column(
            name = "restaurant_id",
            nullable = false,
            updatable = false
    )
    @NotNull
    @Positive
    private Long restaurantId;

    /**
     * Physical table identifier.
     * This comes from Table Service.
     */
    @Column(
            name = "table_id",
            nullable = false,
            updatable = false
    )
    @NotNull
    @Positive
    private Long tableId;

    /**
     * Human-readable table number.
     */
    @Column(
            name = "table_number",
            nullable = false,
            updatable = false
    )
    @NotNull
    @Positive
    private Long tableNumber;

    /**
     * Table session identifier created by Table Service.
     */
    @Column(
            name = "session_id",
            nullable = false,
            updatable = false
    )
    @NotNull
    @Positive
    private Long sessionId;

    /**
     * Session token created and owned by Table Service.
     *
     * Order Service never generates this token.
     */
    @Column(
            name = "session_token",
            nullable = false,
            updatable = false,
            length = 255
    )
    @NotBlank
    private String sessionToken;

    /**
     * Current order status.
     */
    @Enumerated(EnumType.STRING)
    @Column(
            name = "status",
            nullable = false,
            length = 30
    )
    @NotNull
    private OrderStatus status;

    /**
     * Sum of item prices before tax.
     */
    @Column(
            name = "subtotal",
            nullable = false,
            precision = 19,
            scale = 2
    )
    @NotNull
    @DecimalMin(value = "0.00")
    private BigDecimal subtotal;

    /**
     * Tax percentage.
     *
     * Example:
     * 5.00 = 5%
     */
    @Column(
            name = "tax_percentage",
            nullable = false,
            precision = 5,
            scale = 2
    )
    @NotNull
    @DecimalMin(value = "0.00")
    @DecimalMax(value = "100.00")
    private BigDecimal taxPercentage;

    /**
     * Calculated tax amount.
     */
    @Column(
            name = "tax_amount",
            nullable = false,
            precision = 19,
            scale = 2
    )
    @NotNull
    @DecimalMin(value = "0.00")
    private BigDecimal taxAmount;

    /**
     * Final payable amount.
     *
     * totalAmount = subtotal + taxAmount
     */
    @Column(
            name = "total_amount",
            nullable = false,
            precision = 19,
            scale = 2
    )
    @NotNull
    @DecimalMin(value = "0.00")
    private BigDecimal totalAmount;

    /**
     * Indicates whether payment has been completed.
     */
    @Column(
            name = "is_payment",
            nullable = false
    )
    @Builder.Default
    private boolean payment = false;

    /**
     * Payment completion timestamp.
     */
    @Column(name = "paid_at")
    private LocalDateTime paidAt;

    /**
     * Order creation timestamp.
     */
    @CreationTimestamp
    @Column(
            name = "created_at",
            nullable = false,
            updatable = false
    )
    private LocalDateTime createdAt;

    /**
     * Last order modification timestamp.
     */
    @UpdateTimestamp
    @Column(
            name = "updated_at",
            nullable = false
    )
    private LocalDateTime updatedAt;

    /**
     * Completion timestamp.
     */
    @Column(name = "completed_at")
    private LocalDateTime completedAt;

    /**
     * Items belonging to this order.
     */
    @OneToMany(
            mappedBy = "order",
            cascade = CascadeType.ALL,
            orphanRemoval = true
    )
    @OrderBy("id ASC")
    @Builder.Default
    private List<OrderItem> items = new ArrayList<>();

    /**
     * Generates the public order UUID.
     */
    @PrePersist
    protected void generateOrderUUID() {

        if (orderId == null || orderId.isBlank()) {
            orderId = UUID.randomUUID().toString();
        }
    }
}